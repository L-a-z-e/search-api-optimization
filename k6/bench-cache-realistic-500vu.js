function q() {
    const r = Math.random();
    if (r < 0.6) return POPULAR[Math.floor(Math.random() * POPULAR.length)];
    if (r < 0.9) return NORMAL[Math.floor(Math.random() * NORMAL.length)];
    return LONGTAIL[Math.floor(Math.random() * LONGTAIL.length)];
}

